#!/usr/bin/env python3
"""The limits check (QA-22): no rule that stops, refuses, drops or delays work stays secret.

On 6 Nov 2026 the owner's main workflow turned out to refuse any repository over 150 source files: a number nobody had
asked for, in no requirement, shown to nobody. The truncation check (ops/truncation.py) sees text that is cut; this one
sees work that is stopped.

  python3 ops/limits.py check     every limit without its tag, and a docs/LIMITS.md that is out of date; exit 1 (ops/check.sh)
  python3 ops/limits.py write     rewrite docs/LIMITS.md from the tags

A limit is any of, in ops/, images/ and the config scripts:
  - a constant whose name says so (MAX_x, x_MAX, x_LIMIT, x_TIMEOUT, x_BUDGET, x_ATTEMPTS, x_SLOTS ...) set to a number;
  - a shell variable's numeric default of such a name (MAX_x=${MAX_x:-150});
  - a shell comparison with a number or variable that leads to an exit or a refusal;
  - a Python count compared with a number, or a constant, that leads to a raise, a refusal or a skip;
  - a --max-turns given to Claude Code.
Its tag is on the same line or the line above:   # limit: <what it does>, <why it exists>

  waits    the work goes on by itself when the condition clears
  paces    the work is spread out over time and all of it is still done
  refuses  the asker is told at once, with the limit named, and can change the request
  stops    a run past this is ended and reported as such (a guard against something hanging or looping)
  drops    something is left out; the reason must say where that is shown

The tag makes the rule visible in docs/LIMITS.md and to whoever reviews the change. It is the place to ask: did the
owner want this, and what happens to their work when it hits?
Reads only the repository (write: docs/LIMITS.md too). Stdlib only.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = "docs/LIMITS.md"
KINDS = ("waits", "paces", "refuses", "stops", "drops")
WORD = r"(?:MAX|LIMIT|LIMITS|BUDGET|QUOTA|TIMEOUT|DEADLINE|ATTEMPTS|RESTARTS|RETRIES|SLOTS|TRIPS)"
CONST = re.compile(rf"^\s*(?:export\s+|readonly\s+|local\s+)?((?:[A-Z][A-Z0-9_]*_)?{WORD}(?:_[A-Z0-9_]+)?)\s*=\s*\(?(?:\$\{{[A-Z0-9_]+:-)?-?\d")
GROUP = re.compile(rf"^\s*(?:[A-Z][A-Z0-9_]*_)?{WORD}(?:_[A-Z0-9_]+)?\s*,")
SHCMP = re.compile(r"\[\[? *\"?\$\{?#?\w+\}?\"? +-(?:gt|ge|lt|le) +\"?\$?\{?\w+\}?\"? *\]\]?")
PYCMP = re.compile(r"\bif\b.*\b(?:len\([^)]*\)|[a-z_]*(?:count|total|size|files|n))\s*(?:>=?)\s*(?:[A-Z][A-Z0-9_]{2,}|\d{2,})\b")
LEADS = re.compile(r"\braise\b|\brefus|\bexit\b|\bcontinue\b|\bbreak\b|return\s+[f\"'(]")
TURNS = re.compile(r"--max-turns")
TAG = re.compile(r"limit:\s*(\w+)\s*,?\s*(.*?)\s*(?:-->)?$")
SKIP = ("ops/limits.py", "ops/textcap.py", "ops/truncation.py")


def files(root=ROOT):
    p = subprocess.run(["git", "ls-files", "ops", "images", "config", "smoke"], cwd=root, capture_output=True, text=True)
    out = p.stdout.split() if p.returncode == 0 else []
    if not out:
        out = [str(f.relative_to(root)) for d in ("ops", "images", "config", "smoke") for f in sorted((Path(root) / d).rglob("*"))
               if f.is_file() and not {"__pycache__", "node_modules"} & set(f.parts)]
    return sorted(f for f in out if f.endswith((".py", ".sh")) and "/vendor/" not in f and f not in SKIP and (Path(root) / f).exists())


def found(f, lines, i):
    """What limit line i is, or ''."""
    ln = lines[i]
    code = re.sub(r"\s#\s.*$", "", ln)
    if code.lstrip().startswith("#"):
        return ""
    m = CONST.match(code)
    if m:
        return m.group(1)
    if TURNS.search(code):
        return "--max-turns"
    near = "\n".join(lines[i:i + 3])
    if f.endswith(".sh") and SHCMP.search(code) and LEADS.search(near):
        return SHCMP.search(code).group(0)
    if f.endswith(".py") and PYCMP.search(code) and LEADS.search(near):
        return PYCMP.search(code).group(0).removeprefix("if ").strip()
    return ""


def limits(root=ROOT):
    """-> [(file, line, what, kind or None, why)] for every limit in the repository."""
    out = []
    for f in files(root):
        lines = (Path(root) / f).read_text(errors="replace").splitlines()
        for i in range(len(lines)):
            what = found(f, lines, i)
            if not what:
                continue
            tag = TAG.search(lines[i])
            if not tag and i and lines[i - 1].lstrip().startswith("#"):
                tag = TAG.search(lines[i - 1])
            out.append((f, i + 1, what, tag.group(1) if tag else None, tag.group(2) if tag else ""))
    return out


def render(root=ROOT):
    rows = limits(root)
    head = ["# Every limit in the stack", "",
            "What stops, refuses, drops or delays work, each with what it does and why it exists. Generated by",
            "`python3 ops/limits.py write` from the `# limit:` tags in the code; `ops/check.sh` fails on a limit without a tag and",
            "on this page being out of date (QA-22). Text cut for length is a different list: `python3 ops/truncation.py report`.", "",
            "**waits**: goes on by itself when the condition clears. **paces**: spread over time, all of it still done. **refuses**:",
            "the asker is told at once with the limit named. **stops**: a run past this ends and is reported. **drops**: something is",
            "left out, and the reason says where that is shown.", ""]
    body = []
    for kind in KINDS:
        some = [r for r in rows if r[3] == kind]
        if not some:
            continue
        body += [f"## {kind} ({len(some)})", "", "| Where | Limit | Why |", "|---|---|---|"]
        body += [f"| `{f}` | `{what.replace('|', chr(92) + '|')}` | {why.replace('|', chr(92) + '|')} |" for f, _, what, _, why in some]
        body.append("")
    return "\n".join(head + body).rstrip() + "\n"


def problems(root=ROOT):
    out = []
    for f, n, what, kind, why in limits(root):
        if kind not in KINDS:
            out.append(f"{f}:{n}: {what} is a limit without a known tag: # limit: {'|'.join(KINDS)}, why it exists (QA-22)")
        elif len(why) < 10:
            out.append(f"{f}:{n}: {what}: say why it exists after `limit: {kind},` (QA-22)")
    doc = Path(root) / DOC
    if not out and (not doc.exists() or doc.read_text() != render(root)):
        out.append(f"{DOC} is out of date: python3 ops/limits.py write")
    return out


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "check"
    if cmd == "write":
        (ROOT / DOC).write_text(render())
        print(f"{DOC}: {len(limits())} limits")
        return 0
    bad = problems()
    for p in bad:
        print(p)
    print(f"{len(limits())} limits, {len(bad)} problems")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
