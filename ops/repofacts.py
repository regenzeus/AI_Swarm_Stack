#!/usr/bin/env python3
"""A repository's measured facts, and the brief made from them (BLD-27, CHG-19, docs/REPO-KNOWLEDGE.md).

The facts answer where a repository breaks, what changes together, who knows it and how healthy it is, without a model.
CodeLore reads the git history and repowise indexes the code: third-party programs, so each runs sealed (images/repointel:
no network, no secrets, no capabilities, a read-only root) on a throwaway copy that shares no file with the real clone.
If one tool fails the other's results stay, and `errors` says what is unknown. The repository's own code is never run.

  /srv/ai/code-docs/<name>.facts.json  {at, commit, commits, hotspots, coupling, ownership, code_age, health: {sections},
                                       left_out, errors}; what the repo page reads (/api/repo/<name>/facts)
  /srv/ai/state/repofacts/             the locks, a failed commit's mark, and the facts at an exam case's parent commit

A coding agent gets what its task needs in its brief, because a tool it could call is not knowledge it has (77 builds, no
call to the code graph): brief() picks the files, what changes with them, how often, who uses them, the tests, the commands,
the wiki's lines on them and what failed before. It is marked as data and says the code wins.

  python3 ops/repofacts.py build <name>            the facts of one repository now (make facts)
  python3 ops/repofacts.py sync                    rebuild those whose HEAD moved (repofacts-sync.timer), one at a time
  python3 ops/repofacts.py brief <name> <request>  print a brief (no history is changed; files by the request's words)
"""
