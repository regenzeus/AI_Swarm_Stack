def now():
    return time.strftime("%Y-%m-%dT%H:%M:%S")


def env():
    return {**os.environ, "DOCKER_HOST": os.environ.get("DOCKER_HOST", DEPLOY.DOCKER_SOCKET), "GIT_TERMINAL_PROMPT": "0", "GIT_LFS_SKIP_SMUDGE": "1"}


def run(*cmd, timeout=600, input=None):
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, env=env(), input=input)


def git(path, *args, timeout=600, input=None, check=True):
    """Hooks stay off whatever the command."""
    p = run("git", "-c", "core.hooksPath=/dev/null", "-C", str(path), *args, timeout=timeout, input=input)
    if check and p.returncode:
        raise RuntimeError(f"git {args[0]}: {(p.stderr or p.stdout).strip()}")
    return p.stdout.strip()


def said(p):
    return TC.tail((p.stderr or p.stdout or "").strip(), 1500)  # cap: store (what a tool said on failing, for errors)


# ---------- where the facts are ----------
def path(name, at=None):
    return STATE / "at" / f"{name}@{at[:12]}.json" if at else DOCS / f"{name}.facts.json"  # cap: id


def load(name, at=None):
    try:
        doc = json.loads(path(name, at).read_text())
        return doc if isinstance(doc, dict) else None
    except (OSError, ValueError):
        return None


def save(doc, f):
    f.parent.mkdir(parents=True, exist_ok=True)
    tmp = f.with_name(f.name + ".tmp")
    tmp.write_text(json.dumps(doc, ensure_ascii=False))
    tmp.replace(f)


def gaps(doc):
    """What the facts could not find out, in words for the onboarding's status; "" when nothing is unknown (QA-26)."""
    rows = [f"{e.get('analysis') or e.get('tool')}: {TC.cut(e.get('error'), 240)}" for e in (doc or {}).get("errors") or []]  # cap: preview (errors in the facts file and on /api/repo/<name>/facts hold all of it)
    return ("Unknown: " + "; ".join(rows)) if rows else ""


_read = {}


def state_of(name):
    """(facts there?, what they could not find out), for package() and status(), which run on every state write: parsed once per file version."""
    f = path(name)
    try:
        key = (str(f), f.stat().st_mtime_ns)
    except OSError:
        return False, ""
    if _read.get(name, (None,))[0] != key:
        doc = load(name)
        _read[name] = (key, doc is not None, gaps(doc) if doc is not None else "Unknown: the facts file cannot be read")
    return _read[name][1], _read[name][2]


# ---------- the throwaway copy ----------
def full_history(repo, errors):
    """A shallow clone (onboarding used to clone with --depth 1) gets its whole history. If it cannot, the facts say so."""
    if git(repo, "rev-parse", "--is-shallow-repository", check=False) != "true":
        return
    p = run("git", "-c", "core.hooksPath=/dev/null", "-C", str(repo), "fetch", "-q", "--unshallow", timeout=HISTORY_TIMEOUT)
    if git(repo, "rev-parse", "--is-shallow-repository", check=False) == "true":
        errors.append({"tool": "git", "analysis": "", "error": f"the clone holds only part of its history and it could not be fetched: {said(p) or 'it has no remote'}"})


def make_copy(source, at=None):
    """A copy that shares no file with the clone (--no-hardlinks, or chmod and the tools would reach its objects) and knows no
    remote. At a commit: nothing later is reachable in it, so no tool can read an exam's answer."""
    work = Path(tempfile.mkdtemp(prefix="repofacts-", dir=WORK))
    copy = work / "repo"
    (work / "out").mkdir()
    p = run("git", "-c", "core.hooksPath=/dev/null", "clone", "-q", "--no-hardlinks", str(source), str(copy), timeout=HISTORY_TIMEOUT)
    if p.returncode:
        discard(work)
        raise RuntimeError(f"no throwaway copy of {source}: {said(p)}")
    git(copy, "remote", "remove", "origin", check=False)
    if at:
        git(copy, "checkout", "-q", "--detach", at)
        refs = git(copy, "for-each-ref", "--format=delete %(refname)")
        git(copy, "update-ref", "--stdin", input=refs + "\n" if refs else "")
    run("chmod", "-R", "a+rwX", str(work), timeout=300)  # the tools run as their own user; symlinks are not followed
    return work


def discard(work):
    """What a tool wrote belongs to the image's user: what this process cannot remove goes through the image."""
    shutil.rmtree(work, ignore_errors=True)
    if work.exists():
        run("docker", "run", "--rm", "--network", "none", "--user", "0", "--entrypoint", "rm", "-v", f"{work}:/w", IMAGE, "-rf", "/w/repo", "/w/out", timeout=600)
        shutil.rmtree(work, ignore_errors=True)
    if work.exists():
        print(f"could not remove {work}", file=sys.stderr, flush=True)


# ---------- the sealed tools ----------
def sealed(work, label, cmd, memory):
    """One tool in its own container. -> (exit code, what it said). Nothing but the copy and an empty folder is mounted."""
    box = f"{work.name}-{label}"
    argv = ["docker", "run", "--rm", "--name", box, "--network", "none", "--memory", memory, "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
            "--read-only", "--tmpfs", "/tmp", "-v", f"{work / 'repo'}:/repo", "-v", f"{work / 'out'}:/out", "-w", "/repo", IMAGE, *cmd]
    try:
        p = run(*argv, timeout=TOOL_TIMEOUT)
        return p.returncode, said(p)
    except subprocess.TimeoutExpired:
        return 124, f"still running after {TOOL_TIMEOUT // 60} minutes"
    finally:
        run("docker", "rm", "-f", box, timeout=120)


def tool(work, label, cmd):
    """-> None, or why it failed."""
    for memory in MEMORY:
        rc, words = sealed(work, label, cmd, memory)
        if rc != 137:
            break
    if not rc:
        return None
    return f"killed for memory at {memory} of room" if rc == 137 else f"exit {rc}: {words}"


def read_json(f):
    """A tool's result; a link it left there is not followed out of the copy."""
    try:
        return None if f.is_symlink() else json.loads(f.read_text(errors="replace"))
    except (OSError, ValueError):
        return None


def row_of(analysis, fields, r):
    """A tool's row -> the facts' row, by known fields. It is another program's output about untrusted code: only these keys, and paths as text."""
    if not isinstance(r, dict):
        return None
    if analysis == "coupling":
        r = {**r, "a": r.get("entity_a"), "b": r.get("entity_b")}
        return {k: r.get(k) for k in fields} if isinstance(r["a"], str) and isinstance(r["b"], str) else None
    return {k: r.get(k) for k in fields} if isinstance(r.get("path"), str) else None


def codelore(work, errors):
    """The four analyses, each on its own: {facts key: rows}."""
    out = {}
    for analysis, (key, fields) in ANALYSES.items():
        out[key] = []
        target = work / "out" / f"{analysis}.json"
        cmd = ["codelore", "--no-banner", "analyze", "--analysis", analysis, "--repo", ".", "--no-cache", "--rows", str(ROWS),
               *(["--min-revs", "1"] if analysis in EVERY_FILE else []), "--format", "json", "--output", f"/out/{target.name}"]
        why = tool(work, analysis, cmd)
        rows = read_json(target)
        if why or not isinstance(rows, list):
            errors.append({"tool": "codelore", "analysis": key, "error": why or "it wrote no result that can be read"})
            continue
        out[key] = [x for x in (row_of(analysis, fields, r) for r in rows) if x]
        if len(rows) >= ROWS:
            errors.append({"tool": "codelore", "analysis": key, "error": f"only its top {ROWS:,} rows are kept: the repository has more"})
    return out


def repowise(work, errors):
    """The index, then the assessment's sections; the index goes with the copy."""
    why = tool(work, "index", ["repowise", "init", "--yes", "--no-prose", "--no-editor-setup"])
    if not why:
        why = tool(work, "assessment", ["repowise", "report", "assessment", "--format", "json", "--out", "/out/assessment.json"])
    doc = read_json(work / "out" / "assessment.json") if not why else None
    if why or not isinstance(doc, dict) or not isinstance(doc.get("sections"), list):
        errors.append({"tool": "repowise", "analysis": "health", "error": why or "it wrote no assessment that can be read"})
        return {"sections": []}
    keep = lambda c: {k: c.get(k) for k in ("name", "score", "reason", "details", "method", "basis", "data") if k in c}
    sections = [{"id": s.get("id"), "title": s.get("title"), "summary": s.get("summary"), "checks": [keep(c) for c in s.get("checks") or [] if isinstance(c, dict)]}
                for s in doc["sections"] if isinstance(s, dict)]
    return {"sections": sections, "notice": doc.get("notice"), "by": doc.get("generator"), "made": doc.get("generated_at")}


def generated_in(copy, paths):
    """Files the repository itself marks as generated: linguist-generated, or a generated-file line at their top."""
    if not paths:
        return set()
    out = set()
    said_attr = git(copy, "check-attr", "--stdin", "linguist-generated", input="\n".join(sorted(paths)) + "\n", check=False)
    for ln in said_attr.splitlines():
        p, _, value = ln.rpartition(": ")
        if value in ("true", "set"):
            out.add(p.rsplit(": linguist-generated", 1)[0])
    for p in paths - out:
        f = copy / p
        try:
            if not f.is_symlink() and f.is_file():
                with f.open(errors="replace") as h:
                    if GENERATED.search(h.read(600)):  # cap: parse (the top of a file; nothing of it is kept)
                        out.add(p)
        except (OSError, ValueError) as e:
            print(f"{p}: {type(e).__name__}", file=sys.stderr, flush=True)
    return out


def meaningful(rows, here, generated):
    """Coupling that says something: both files are still here, and neither is a lockfile, a changelog or generated, which change with everything. -> (kept, left out)."""
    says = lambda p: p in here and p not in generated and not SAYS_NOTHING.search(p)
    keep = [r for r in rows if says(r["a"]) and says(r["b"])]
    return keep, len(rows) - len(keep)


# ---------- one run ----------
class locked:
    """One run at a time on the PC: its memory is shared. A flock goes with the process if it dies."""

    def __init__(self, name, wait=True):
        self.name, self.wait, self.f = name, wait, None

    def __enter__(self):
        STATE.mkdir(parents=True, exist_ok=True)
        self.f = (STATE / f".{self.name}.lock").open("a")
        try:
            fcntl.flock(self.f, fcntl.LOCK_EX | (0 if self.wait else fcntl.LOCK_NB))
            return True
        except OSError:
            return False

    def __exit__(self, *a):
        self.f.close()


def build(name, source=None, at=None):
    """The facts of a repository, written and returned; of a commit in another clone with `at` (an exam's parent commit). A
    tool's failure is in errors and leaves the other's results; only no copy at all raises. The real clone stays as it is, but
    for a shallow clone's history, and is never mounted anywhere."""
    repo, errors = Path(source) if source else CODE / name, []
    with locked("build"):
        for old in WORK.glob("repofacts-*"):               # a crash's leftovers: under the lock no run is using one
            discard(old)
        if not at:
            full_history(repo, errors)
        work = make_copy(repo, at)
        copy = work / "repo"
        try:
            # git asks the copy only before a tool has run: a .git/config a tool wrote could make git run a command, unsealed
            commit, commits = git(copy, "rev-parse", "HEAD"), int(git(copy, "rev-list", "--count", "HEAD"))
            here = set(git(copy, "ls-files").splitlines())
            generated = generated_in(copy, here)
            history = codelore(work, errors)
            coupling, left_out = meaningful(history["coupling"], here, generated)
            health = repowise(work, errors)
        finally:
            discard(work)
    doc = {"at": now(), "commit": commit, "commits": commits, "hotspots": history["hotspots"], "coupling": coupling, "ownership": history["ownership"],
           "code_age": history["code_age"], "health": health, "left_out": {"coupling": left_out}, "errors": errors}
    save(doc, path(name, at))
    return doc


def at_commit(name, source, at):
    """The facts as they stood at a commit, kept for the next run of the same case: an exam's arm must not read the future."""
    return load(name, at) or build(name, source=source, at=at)


def nothing(doc):
    """No tool found anything: a failed try, not a result."""
    return not any(doc.get(k) for k in ("hotspots", "coupling", "ownership", "code_age")) and not doc["health"].get("sections") and bool(doc.get("errors"))


def forget(name):
    for f in (path(name), STATE / f"{name}.failed", *STATE.glob(f"at/{name}@*.json")):
        f.unlink(missing_ok=True)
    _read.pop(name, None)


# ---------- staying current ----------
def stale(name):
    """HEAD moved since the facts, as the code graph is kept (ops/graphify-sync.sh); facts with an unknown part get another go after RETRY."""
    head = git(CODE / name, "rev-parse", "HEAD", check=False)
    if not head:
        return False
    mark = STATE / f"{name}.failed"
    if mark.exists() and mark.read_text().strip() == head:
        return False                                       # failed at this commit: the next try comes with the next one
    doc = load(name)
    if not doc or doc.get("commit") != head:
        return True
    return bool(doc.get("errors")) and time.time() - path(name).stat().st_mtime > RETRY


def free_gb():
    import conductor as CD
    return CD.free_gb()


def sync():
    """Every repository in ~/code whose facts lag, one after the other; a scratch repository of a trial has none of its own."""
    STATE.mkdir(parents=True, exist_ok=True)
    with locked("sync", wait=False) as mine:
        if not mine:
            return 0
        for d in sorted(CODE.iterdir()) if CODE.exists() else ():
            if not (d / ".git").exists() or d.name.startswith("trial-") or not stale(d.name):
                continue
            if free_gb() < NEED_GB:
                print(f"facts of {d.name} wait for memory", flush=True)
                return 0
            try:
                doc = build(d.name)
                (STATE / f"{d.name}.failed").unlink(missing_ok=True)
                print(f"{time.strftime('%F %T')} facts of {d.name}: {doc['commits']} commits. {gaps(doc)}".rstrip(), flush=True)
            except (RuntimeError, OSError, subprocess.SubprocessError) as e:
                (STATE / f"{d.name}.failed").write_text(git(CODE / d.name, "rev-parse", "HEAD", check=False) + "\n")
                print(f"facts of {d.name} FAILED: {e}", file=sys.stderr, flush=True)
    return 0


# ---------- for the wiki's first version ----------
def seed_text(doc):
    """What the wiki's Fragile areas page cites: the measured facts, with the commit they hold at."""
    if not doc:
        return ""
    rows = [f"## Measured facts: its git history and code index (repository facts at commit {str(doc.get('commit'))[:12]}, {doc.get('commits')} commits)",  # cap: id
            "Cite them as the evidence on the Fragile areas page, for example: facts at commit, hotspots."]
    if doc.get("hotspots"):
        rows += ["### Often changed and complex"] + [f"- {r['path']}: {r.get('revisions')} changes, hotspot score {round(r.get('hotspot_score') or 0, 1)}" for r in doc["hotspots"][:15]]  # cap: top
    if doc.get("coupling"):
        rows += ["### What changes together"] + [f"- {r['a']} and {r['b']}: {r.get('shared')} changes together, {round(r.get('degree') or 0)} %" for r in doc["coupling"][:15]]  # cap: top
    checks = [c for s in (doc.get("health") or {}).get("sections") or [] if s.get("id") in ("hotspots", "bus-factor", "dead-code", "test-reach")
              for c in s.get("checks") or [] if ":" not in str(c.get("name")) and c.get("reason")]
    if checks:
        rows += ["### Health"] + [f"- {c['name']}: {c['reason']}" for c in checks]
    if doc.get("errors"):
        rows += [f"Unknown, because a tool could not run: {gaps(doc)}"]
    return "\n".join(rows)


# ---------- the brief ----------
def sections_of(digest):
    """The code map's digest -> {file: what it says about it}."""
    out = {}
    for block in re.split(r"^### ", digest.partition("## Files")[2], flags=re.M)[1:]:
        head, _, body = block.partition("\n")
        out[head.strip()] = body
    return out


def best_matches(name, request, known):
    """The files the request's own words point at, from the code map's digest (else the file names): a word in few files says more,
    and in a file's path more than in its description."""
    f = DOCS / f"{name}.md"
    about = sections_of(f.read_text(errors="replace")) if f.is_file() else {}
    pool = {p: about.get(p, "") for p in (known or about)}
    words = {re.sub(r"(ing|ed|es|s)$", "", w) if len(w) > 5 else w for w in {w.lower() for w in WORDS.findall(request or "")} - COMMON}   # onboarding finds onboard.py
    texts = {p: (p.lower(), body.lower()) for p, body in pool.items()}
    scores = {}
    for w in words:
        found = [p for p, (lp, lb) in texts.items() if w in lp or w in lb]
        rare = math.log(1 + len(pool) / max(1, len(found)))
        for p in found:
            scores[p] = scores.get(p, 0) + rare * (4 if w in texts[p][0] else 1)
    ranked = sorted(scores, key=lambda p: (-scores[p], p))
    return [p for p in ranked if scores[p] >= scores[ranked[0]] * 0.4][:BRIEF_FILES] if ranked else []  # cap: top (the most a brief names)


def named_list(names, n, what=""):
    """Names for one line, with how many more."""
    names = list(names)
    return ", ".join(names[:n]) + (f" (+{len(names) - n}{what})" if len(names) > n else "")  # cap: top (a line of the brief)


def about_file(f, doc, rank, edges, tests, known):
    """One file's line: how often it changes, what changes with it, who uses it, its tests. Say unknown where nothing could tell."""
    bits = []
    if doc:
        revs = next((r.get(k) for k, rows in (("revisions", doc["hotspots"]), ("total_revs", doc["ownership"])) for r in rows if r["path"] == f), None)
        age = next((r for r in doc.get("code_age") or [] if r["path"] == f), None)
        if revs:
            bits.append(f"changed in {revs} of {doc.get('commits')} commits" + (f", hotspot {rank[f]} of {len(rank)}" if f in rank else "")
                        + (f", last on {age.get('last_modified')}" if age else ""))
        else:
            bits.append("no recorded changes" + (" (a new file?)" if known and f not in known else ""))
        pairs = sorted(((r["b"] if r["a"] == f else r["a"], r) for r in doc["coupling"] if f in (r["a"], r["b"])), key=lambda x: -(x[1].get("degree") or 0))
        pairs = [(p, r) for p, r in pairs if not known or p in known]
        if pairs:
            bits.append("changes with " + named_list((f"{p} ({round(r.get('degree') or 0)} %)" for p, r in pairs), BRIEF_WITH))
    else:
        pairs = []
        bits.append("how often it changes: unknown")
    if edges is not None:
        users = sorted(((n, a) for (a, b), n in edges.items() if b == f and (not known or a in known) and not PROSE.search(a)), key=lambda x: (-x[0], x[1]))
        bits.append("used by " + (named_list((a for _, a in users), BRIEF_USED_BY) or "no code the graph knows"))
    found = sorted({*(tests or {}).get(f, []), *(p for p, _ in pairs if TEST_PATH.search(p))} - {f})   # tests that import it, and tests that change with it
    if tests is not None or found:
        bits.append("tests: " + (named_list(found, BRIEF_WITH) or "none found"))
    return f"- {f}: " + "; ".join(bits)


BRIEF_TESTS_FIRST = 12   # limit: drops, tests to run first past these are counted, not named (the whole suite runs at the end anyway)
BRIEF_USERS = 8          # limit: drops, users of the changed files whose tests are looked up past these (the most linked first)


def tests_first(code, chosen, edges, tests, known):
    """DEC-49: the tests to run first: those of the chosen files, then those of the files that use them (the impact a change has)."""
    if tests is None:
        return []
    out = [t for f in chosen for t in tests.get(f, [])]
    if edges:
        users = {}
        for (a, b), n in edges.items():
            if b in chosen and a not in chosen and (not known or a in known) and not TEST_PATH.search(a) and not PROSE.search(a):
                users[a] = users.get(a, 0) + n
        top = [a for a, _ in sorted(users.items(), key=lambda x: (-x[1], x[0]))[:BRIEF_USERS]]  # cap: top (BRIEF_USERS)
        try:
            more = tests_of(code, top, known) or {}
        except (OSError, RuntimeError, subprocess.SubprocessError):
            more = {}
        out += [t for a in top for t in more.get(a, [])]
    out += [f for f in chosen if TEST_PATH.search(f) and (not known or f in known)]
    return list(dict.fromkeys(out))


def examples(chosen, known, changed=None):
    """DEC-49: for a file the task makes new, the closest existing file to write it like: same folder and kind, else the nearest
    folder up that has one; among those, the one sharing most of its name, then the most recently changed (today's conventions).
    Conventions are copied best from a real example."""
    changed = changed or {}
    if not known:
        return []
    out = []
    for f in chosen:
        if f in known or "." not in Path(f).name:
            continue
        suffix, folder, test = Path(f).suffix, Path(f).parent, bool(TEST_PATH.search(f))
        best = None
        while best is None:
            here = sorted(k for k in known if Path(k).parent == folder and Path(k).suffix == suffix and bool(TEST_PATH.search(k)) == test
                          and Path(k).name not in ("__init__.py", "conftest.py"))
            if here:
                stem = set(re.split(r"[_\-.]", Path(f).stem))
                best = max(here, key=lambda k: (len(stem & set(re.split(r"[_\-.]", Path(k).stem))), changed.get(k, ""), -len(k)))
            elif str(folder) in ("", "."):
                break
            else:
                folder = folder.parent
        if best:
            out.append(f"- {f} is new: write it like {best} (the same kind of file{' in the same folder' if Path(best).parent == Path(f).parent else ' nearest to it'})")
    return out


def tests_of(code, files, known):
    """{file: test files that import its module or name its path}, read from the repository's main (a working copy may stand on an old
    branch); None when it keeps no tests/ folder."""
    import codegraph as CG
    import repowiki as RW
    if known and not any(p.startswith("tests/") for p in known):
        return None
    ref, out, esc = RW.ref_of(code), {}, lambda s: re.sub(r"([.^$*+?()\[\]{}|\\])", r"\\\1", s)
    for f in files:
        mod, end = esc(CG.module_of(f)), "([^A-Za-z0-9_]|$)"
        pattern = f"^[[:space:]]*(import|from)[[:space:]]+{mod}{end}|import[[:space:]](.*[^A-Za-z0-9_])?{mod}{end}|{esc(f)}"
        found = RW.git(code, "grep", "-l", "-E", pattern, ref, "--", "tests")
        out[f] = sorted(x.split(":", 1)[1] for x in found.splitlines() if ":" in x)
    return out


def wiki_lines(name, files):
    """The wiki's fact lines that name these files, the ones on what failed apart. -> (failed before, the rest, the newest lessons)."""
    import repowiki as RW
    m, failed, rest, newest = RW.mm(), [], [], []
    folder = RW.folder(name)
    for f in sorted(folder.glob("*.md")) if folder.is_dir() else ():
        if f.stem == "index":
            continue
        meta, body = m.split_front(f.read_text(errors="replace"))
        if meta.get("made_by") == "onboarding":         # onboarding's own pages restate the code map: the brief has it already
            continue
        lines = [ln for ln in re.split(r"^## Superseded", body, flags=re.M)[0].splitlines() if ln.startswith("- ")]
        note = f"{meta.get('title', f.stem)}, commit {meta.get('commit', '?')}" + (", to re-verify" if meta.get("reverify") else "")
        hits = [ln for ln in lines if any(x in ln for x in files)]
        (failed if f.stem in ("fragile", "lessons") else rest).extend(f"- {TC.cut(ln[2:], 500)} [{note}]" for ln in hits)  # cap: prompt (the page has all of it)
        if f.stem in ("fragile", "lessons"):
            newest.extend(f"- {TC.cut(ln[2:], 500)} [{note}]" for ln in lines[-3:] if ln not in hits)  # cap: prompt (the page has all of it)
    return failed, rest, newest


def failed_builds(names, files):
    """Builds of this repository that failed or were rejected after touching these files, with the reason."""
    import repowiki as RW
    c = RW.mm().db()
    marks = ",".join("?" * len(names))
    try:
        rows = c.execute(f"select id, status, title, error, feedback, files from builds where repo in ({marks}) and status in ('failed','rejected') order by id desc limit {FAILED_BUILDS}", names).fetchall()  # cap: parse (only those that touched these files are shown)
    finally:
        c.close()
    out = []
    for r in rows:
        try:
            touched = {x[-1] for x in json.loads(r["files"] or "[]")}
        except (ValueError, TypeError, IndexError):
            touched = set()
        if touched & set(files):
            why = re.sub(r"\s+", " ", str(r["error"] or r["feedback"] or "no reason recorded")).strip()
            out.append(f"- build #{r['id']} {r['status']}, {r['title']}: {TC.cut(why, 300)}")  # cap: prompt (the build's page has all of it)
    return out


def brief(name, request, files=None, budget=BRIEF, code=None, at=None):
    """What a coding step needs to know for this task, within a budget. `name` is whose knowledge it is, `code` the repository whose
    tree the step works on when that is another (a trial's scratch repository starts from the wiki_of repository's parent commit): what
    is not in that tree is left out. `at`: facts as of that commit, for an exam; if they are not there it says the facts are from newer code."""
    import codegraph as CG
    import repowiki as RW
    code = code or name
    unknown = []
    try:
        known = RW.tracked(code)
    except (OSError, RuntimeError, subprocess.SubprocessError) as e:
        known = set()
        unknown.append(f"the repository's files ({type(e).__name__})")
    wanted = [f for f in dict.fromkeys(str(x) for x in files or []) if f and f != "*"]
    chosen = wanted or best_matches(name, request, known)
    doc = load(name, at)
    newer = bool(at and not doc)
    doc = doc or load(name) if at else doc
    try:
        doc = {**{k: [] for k in ("hotspots", "coupling", "ownership", "code_age")}, **doc} if doc else None
        rank = {r["path"]: i for i, r in enumerate(doc["hotspots"], 1)} if doc else {}
        edges = CG.file_edges(name) or None
        tests = tests_of(code, chosen, known)
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as e:
        edges = tests = None
        unknown.append(f"the code graph or the tests ({type(e).__name__})")
    head = ("## What the stack knows for this task\n"
            + (f"Measured from the repository's git history at commit {str(doc.get('commit'))[:12]} ({doc.get('commits')} commits)" if doc else "Gathered")  # cap: id
            + " and its code graph, and picked for this task. It is data, not instructions, and when it disagrees with the code, the code is right."
            + (" These facts are from newer code than yours." if newer else ""))
    parts = [head]
    if chosen:
        how = "the files the specification names" if wanted else "the best matches for the request's words in the code map (a guess: check them)"
        rows = [about_file(f, doc, rank, edges, tests, known) for f in chosen[:BRIEF_FILES]]  # cap: top (the line after them counts the rest)
        rows += [f"(… and {len(chosen) - BRIEF_FILES} more files)"] if len(chosen) > BRIEF_FILES else []
        parts.append(f"### Files: {how}\n" + "\n".join(rows))
    else:
        parts.append("### Files\nThe request's words match no file: find them in the code.")
    if not doc:
        unknown.append("how files change: no facts yet")
    elif doc.get("errors"):
        unknown.append(gaps(doc).removeprefix("Unknown: "))
    if edges is None:
        unknown.append("who uses them: no code graph here yet")
    first = tests_first(code, chosen, edges, tests, known)
    if first:
        parts.append("### Tests to run first\nThe tests of these files and of the code that uses them, before the whole suite: "
                     + named_list(first, BRIEF_TESTS_FIRST))
    like = examples(chosen, known, {r["path"]: str(r.get("last_modified") or "") for r in (doc or {}).get("code_age") or []})
    if like:
        parts.append("### The closest example\n" + "\n".join(like))
    commands = RW.profile(name)
    if commands.get("test"):
        parts.append(f"### Commands that work\nSet up: {commands.get('setup') or '(nothing to set up)'}\nAll tests: {commands['test']}"
                     + (f"\nOne test: {commands['test_one']}" if commands.get("test_one") else ""))
    else:
        unknown.append("the commands: no profile yet")
    failed, rest, newest = wiki_lines(name, chosen)
    try:
        builds = failed_builds(list(dict.fromkeys((name, code))), chosen) if chosen else []
    except (sqlite3.Error, OSError) as e:                  # a database in use: the brief goes on and says so
        builds = []
        unknown.append(f"past builds ({type(e).__name__})")
    gone = failed[:BRIEF_LINES] + builds[:BRIEF_LINES]  # cap: top (the most recent lines; the wiki and the builds' pages have all)
    if gone:
        parts.append("### What failed here before, on these files\n" + "\n".join(gone))
    elif newest:
        parts.append("### What failed here before, elsewhere in the repository\n" + "\n".join(newest[-3:]))
    if rest:
        parts.append("### The wiki on these files\n" + "\n".join(rest[:BRIEF_LINES]))  # cap: top (the vault has every page)
    if unknown:
        parts.append("### Unknown\n" + "; ".join(unknown))
    return TC.cut("\n\n".join(parts), budget, f"the whole facts are in {path(name).name}, the wiki in vault/repos/{name}/wiki")  # cap: prompt


