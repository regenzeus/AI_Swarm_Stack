def test_a_repository_s_requirements_are_read_as_data_never_imported(tmp_path):
    """codegraph.requirements_for imported the repository's own ops/req.py into the runner: its code would have run there."""
    import codegraph as CG
    (tmp_path / "ops").mkdir()
    (tmp_path / "ops/req.py").write_text("open(__file__ + '.ran', 'w').write('x')\n")
    (tmp_path / "requirements").mkdir()
    (tmp_path / "requirements/a.yaml").write_text("items:\n  - id: X-1\n    verify: {method: test, by: [tests/test_a.py::t]}\n")
    assert CG.requirements_for(tmp_path, {"tests/test_a.py"}, set()) == {"tests/test_a.py": ["X-1"]}
    assert not (tmp_path / "ops/req.py.ran").exists()
