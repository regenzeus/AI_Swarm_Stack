def gitc(p, *a):
    return subprocess.run(["git", "-C", str(p), *a], check=True, capture_output=True, text=True).stdout.strip()


def commit(repo, message="a change", **files):
    for rel, text in files.items():
        f = repo / rel.replace("__", "/")
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)
    gitc(repo, "add", "-A")
    gitc(repo, "commit", "-qm", message)


def snapshot(root):
    """Every path of a tree with its mode, its time and its bytes."""
    out = {}
    for f in sorted(Path(root).rglob("*")):
        st = f.lstat()
        out[str(f.relative_to(root))] = (st.st_mode, st.st_mtime_ns, f.read_bytes() if f.is_file() else None)
    return out


