def test_a_killed_tool_gets_more_room_once_and_a_hang_is_stopped_and_said(F, monkeypatch):
    real = RF.run
    runs = []

    def killed_once(*cmd, **k):
        if cmd[0] == "docker" and cmd[1] == "run" and "repowise" in cmd and "init" in cmd:
            runs.append(cmd[cmd.index("--memory") + 1])
            if len(runs) == 1:
                return subprocess.CompletedProcess(cmd, 137, "", "")
        return real(*cmd, **k)

    monkeypatch.setattr(RF, "run", killed_once)
    assert RF.build("tool")["errors"] == [] and runs == ["2g", "4g"]

    def hangs(*cmd, **k):
        if cmd[0] == "docker" and cmd[1] == "run" and "repowise" in cmd and "init" in cmd:
            raise subprocess.TimeoutExpired(cmd, 1)
        return real(*cmd, **k)

    monkeypatch.setattr(RF, "run", hangs)
    doc = RF.build("tool")
    assert doc["hotspots"] and "still running" in doc["errors"][0]["error"]
    assert any(c[1] == "rm" and "-f" in c for c in F.calls)                   # the container does not outlive it


