def test_neither_tool_can_touch_the_real_clone(F):
    before = snapshot(F.real)
    objects = {f.stat().st_ino for f in (F.real / ".git/objects").rglob("*") if f.is_file()}
    seen = {}

    def look(tool, copy, out):
        seen.setdefault("inodes", {f.stat().st_ino for f in (copy / ".git/objects").rglob("*") if f.is_file()})
        seen["remotes"] = gitc(copy, "remote")

    F.on_tool = look
    RF.build("tool")
    assert snapshot(F.real) == before and gitc(F.real, "status", "--porcelain") == ""
    assert not seen["inodes"] & objects and seen["remotes"] == ""             # no hard link back, no way to its origin
    assert not (F.tmp / "hook-ran").exists() and not (F.tmp / "config-ran").exists()   # what a tool wrote into the copy's .git never ran
    runs = [c for c in F.calls if c[1] == "run"]
    assert len(runs) == 6 and not list(RF.WORK.glob("repofacts-*"))           # four analyses, the index, the report; the copy is gone
    for c in runs:
        assert all(str(F.real) not in x for x in c)
        for flag in (("--network", "none"), ("--cap-drop", "ALL"), ("--security-opt", "no-new-privileges"), ("--memory", "2g")):
            assert flag[1] == c[c.index(flag[0]) + 1]
        assert "--read-only" in c and "-e" not in c and "--env" not in c       # no secret gets in


